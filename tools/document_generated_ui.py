#!/usr/bin/env python3
"""Add class and method documentation as part of Qt form/resource generation."""
import ast
from pathlib import Path
import xml.etree.ElementTree as ET


def document_source(path, widget_type=None):
    """Document generated Qt declarations without changing their executable statements.

    @param path [Path] Generated Python form or resource source file.
    @param widget_type [str, None] Qt root widget type; None denotes a resource module.
    @return [None] Update the generated file in place.
    """
    source = path.read_text(encoding='utf-8')
    tree = ast.parse(source)
    edits = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.ClassDef, ast.FunctionDef)) or ast.get_docstring(node):
            continue
        if isinstance(node, ast.ClassDef):
            description = ('Generated Qt form used by the handwritten window controller.\n\n'
                           'Store widget, layout and action references named by the source .ui form;\n'
                           'the controller owns application behavior and localized window texts.')
        elif node.name in ('setupUi', 'retranslateUi') and widget_type:
            parameter = node.args.args[1].arg
            description = ('Create widgets, layouts and generated signal connections.' if node.name == 'setupUi'
                           else 'Apply the source form captions generated by pyuic6.')
            description += (f'\n\n@param {parameter} [{widget_type}] Root widget supplied by the window controller.'
                            '\n@return [None] Update the supplied widget in place.')
        elif node.name in ('qInitResources', 'qCleanupResources'):
            description = ('Register the generated binary resources with Qt.' if node.name == 'qInitResources'
                           else 'Unregister the generated binary resources from Qt.')
            description += '\n\n@return [None] Update the Qt resource registry.'
        else:
            continue
        indent = ' ' * (node.col_offset + 4)
        text = indent + '"""' + description.replace('\n', '\n' + indent) + '"""\n'
        text = '\n'.join(line.rstrip() for line in text.split('\n'))
        edits.append((node.body[0].lineno - 1, text))
    lines = source.splitlines(keepends=True)
    for offset, text in sorted(edits, reverse=True):
        lines[offset:offset] = [text]
    path.write_text(''.join(lines), encoding='utf-8')


def main():
    """Document maintained generated forms and resource modules after updateui.sh.

    @return [None] Update only generated files whose corresponding sources exist.
    """
    root = Path(__file__).resolve().parents[1]
    forms = ('ElPartsMain', 'AppsPathSetup', 'ElOpenFileWnd', 'ElHdrEditWnd', 'ElPluginsWnd', 'ElUnitsWnd')
    outputs = ('ElParts', 'ElAppPathWnd', 'ElOpenFileWnd', 'ElHdrEditWnd', 'ElPluginsWnd', 'ElUnitsWnd')
    for form, output in zip(forms, outputs):
        widget = ET.parse(root / 'qt' / (form + '.ui')).getroot().find('widget')
        document_source(root / (output + '.py'), widget.attrib['class'])
    for name in ('resources.py', 'resources.pyx'):
        document_source(root / name)


if __name__ == '__main__':
    main()
